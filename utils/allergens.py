def _normalize(term: str) -> str:
    """Привести аллерген к корню: «орехи» → «орех», «молоко» → «молок»."""
    token = (term or "").lower().strip()
    return token[:-1] if len(token) > 4 else token


def sources_for(term: str) -> List[str]:
    """Слова-маркеры продуктов, содержащих указанный аллерген."""
    root = _normalize(term)
    if root in ALLERGEN_SOURCES:
        return ALLERGEN_SOURCES[root]
    for key, words in ALLERGEN_SOURCES.items():
        if root and (root in key or key in root):
            return words
    # Неизвестный аллерген: ищем хотя бы по самому слову.
    return [root] if root else []


def product_conflicts(
    product_name: str,
    allergies: Optional[List[str]] = None,
    dietary_preferences: Optional[List[str]] = None,
) -> Optional[str]:
    """
    Проверить продукт на конфликт с ограничениями пользователя.

    Возвращает название нарушенного ограничения или None, если продукт подходит.
    """
    name = (product_name or "").lower()
    if not name:
        return None

    for allergen in allergies or []:
        root = _normalize(allergen)
        if root and root in name:
            return allergen
        if any(word in name for word in sources_for(allergen)):
            return allergen

    for preference in dietary_preferences or []:
        root = _normalize(preference)
        for key, excluded in DIET_EXCLUSIONS.items():
            if root and (root in key or key in root):
                if any(word in name for word in excluded):
                    return preference

    return None
